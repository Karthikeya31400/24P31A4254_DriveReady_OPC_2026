# --- Domain Data & Pydantic Schema ---
CATALOGUE = {
    "brahmi guide": 0,
    "grantha guide": 0,
    "alqueva route": 250,
    "st. peter route": 200,
}

HOURS = {
    "monday": "9 am to 6 pm",
    "tuesday": "9 am to 6 pm",
    "wednesday": "9 am to 6 pm",
    "thursday": "9 am to 6 pm",
    "friday": "9 am to 6 pm",
    "saturday": "10 am to 5 pm",
    "sunday": "Closed (Digital App Available 24/7)",
}

class HeritageBooking(BaseModel):
    """A heritage route booking or script guide request from a user's message."""
    name: str = Field(description="Visitor's first name")
    item: Literal["brahmi guide", "grantha guide", "alqueva route", "st. peter route"] = Field(
        description="Requested script guide or Sacred Landscape Route"
    )
    qty: int = Field(description="Number of passes or copies requested", ge=1)
    date: str = Field(description="Preferred visit or access date as stated by the user")
    language: Literal["English", "Telugu"] = Field(
        default="English",
        description="Preferred guide language ('English' or 'Telugu')"
    )

# --- Tools ---
@tool
def get_access_fee(item: str, qty: int = 1) -> str:
    """Get the total access fee in rupees for a KLG script guide or Sacred Landscape Route.

    Args:
        item: Catalogue item, e.g. "brahmi guide", "grantha guide", "alqueva route", or "st. peter route"
        qty: Number of passes or copies requested
    """
    fee = CATALOGUE.get(item.lower().strip())
    if fee is None:
        return f"'{item}' is not in our catalogue. Available: {', '.join(CATALOGUE)}."
    return f"{qty} x {item} = Rs {fee * qty}"

@tool
def is_open(day: str) -> str:
    """Check KLG Ancient World research desk and guided route hours for a day of the week, e.g. 'sunday'."""
    hours = HOURS.get(day.lower().strip())
    return f"KLG desk hours on {day}: {hours}." if hours else f"'{day}' is not a valid day of the week."

@tool
def log_booking(name: str, item: str, qty: int, date: str, language: str = "English") -> str:
    """Save a confirmed KLG Ancient World route booking or script guide request to Google Sheets.
    Use ONLY when the user has provided their name, item, quantity, and preferred date."""
    normalized_item = item.lower().strip()
    if normalized_item not in CATALOGUE:
        return f"'{item}' is not in our catalogue. Available: {', '.join(CATALOGUE)}."

    try:
        booking = HeritageBooking(
            name=name.strip(),
            item=normalized_item,
            qty=qty,
            date=date.strip(),
            language=language if language in ("English", "Telugu") else "English"
        )
    except Exception as e:
        return f"Could not save booking: {e}. Ask the user to clarify."

    total = CATALOGUE[booking.item] * booking.qty
    ws.append_row([booking.name, booking.item, booking.qty, booking.date, booking.language, total])
    return f"Saved: {booking.qty} x {booking.item} ({booking.language}) for {booking.name} on {booking.date}, Rs {total}."

# --- System Prompt & Agent ---
SYSTEM = """ROLE:   You are the friendly heritage assistant for KLG Ancient World (klgancientworld.com).
RULES:  Use get_access_fee for pass/guide fees and is_open for research desk hours; never guess them.
        For questions about scripts, narratives, Sacred Landscape Routes, MythiLens, or policies,
        always use search_klg_kb and answer ONLY from what it returns.
        If the answer isn't in search_klg_kb or tools, reply: "I'll check with the KLG team."
        Before calling log_booking, make sure you have name, item, quantity, and date; ask if missing.
        After saving a booking, read the details back with the total.
FORMAT: Under 60 words, friendly, English or Telugu matching the user."""

agent = create_agent(
    model=llm,
    tools=[get_access_fee, is_open, log_booking, search_klg_kb],
    system_prompt=SYSTEM,
    checkpointer=InMemorySaver()
)

def chat(thread_id: str, text: str) -> str:
    config = {"configurable": {"thread_id": thread_id}}
    try:
        result = agent.invoke({"messages": [{"role": "user", "content": text}]}, config)
        raw_content = result["messages"][-1].content
        # Extract text content if it is formatted as a structured list/dict
        if isinstance(raw_content, list) and len(raw_content) > 0:
            if isinstance(raw_content[0], dict) and "text" in raw_content[0]:
                return raw_content[0]["text"]
        return str(raw_content)
    except Exception as e:
        print("Agent error:", e)
        return "Sorry, I'm a little busy. Please try again in a minute."

