def run_agent_tests(csv_path: str = "/content/test.csv") -> float:
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    passed = 0
    for idx, row in enumerate(rows, start=1):
        q = row["question"]
        expected = row["must_include"].lower()
        # Fresh thread_id per test case prevents memory leakage across rows
        reply = chat(f"eval_thread_{idx}", q)
        ok = expected in reply.lower()
        passed += int(ok)
        status = "PASS" if ok else "FAIL"
        print(f"[{status}] Q: {q}\n       Expected: '{row['must_include']}' | Got: {reply}\n")

    rate = passed / len(rows) if rows else 0.0
    print(f"Sign-off Score: {passed}/{len(rows)} passed ({rate:.0%})")
    return rate

